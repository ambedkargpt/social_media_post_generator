// Samajwadi and Congress have their own vocabulary for the same posts.
// Every other party in the list gets neutral wording.
export function partyKey(party) {
  const p = (party || '').toLowerCase();
  if (p.includes('samajwadi')) return 'sp';
  if (p.includes('indian national congress') || p.includes('(inc)')) return 'inc';
  return 'generic';
}

// Falls back along two axes, party then language, so a role that is missing
// either still reads as something rather than as nothing.
export function roleLabel(role, party, lang) {
  const key = partyKey(party);
  if (lang === 'hi') return role[`${key}_hi`] || role.generic_hi || role[key] || role.generic;
  return role[key] || role.generic;
}

export function labelForId(id, party, lang) {
  for (const g of ROLE_GROUPS) {
    const hit = g.roles.find((r) => r.id === id);
    if (hit) return roleLabel(hit, party, lang);
  }
  return '';
}

// Which group a stored id belongs to, so reopening the form can preselect
// the level someone chose last time rather than making them find it again.
export function groupForId(id) {
  const g = ROLE_GROUPS.find((grp) => grp.roles.some((r) => r.id === id));
  return g ? g.group : '';
}

export function rolesInGroup(group) {
  const g = ROLE_GROUPS.find((grp) => grp.group === group);
  return g ? g.roles : [];
}
