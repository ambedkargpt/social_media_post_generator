const SEP = ' -> ';

// One half of an option, or a bare value stored without its description.
function part(map, text) {
  const key = String(text ?? '').trim();
  return map[key] ?? key;
}

// The whole option in the site language. English is returned untouched, so
// this is safe to call without checking the language first.
export function optionLabel(option, lang) {
  const text = String(option ?? '');
  if (lang !== 'hi' || !text) return text;
  if (!text.includes(SEP)) return part(OPTION_LABELS_HI, text);
  const [label, desc] = text.split(SEP);
  return part(OPTION_LABELS_HI, label) + SEP + part(OPTION_DESCRIPTIONS_HI, desc);
}

// Just the label half, for buttons and chips that drop the description.
export function optionShortLabel(option, lang) {
  const text = String(option ?? '');
  const label = text.includes(SEP) ? text.split(SEP)[0] : text;
  return lang === 'hi' ? part(OPTION_LABELS_HI, label) : label.trim();
}

// The question itself ("Who is the primary audience?").
export function questionLabel(text, lang) {
  const q = String(text ?? '').trim();
  if (lang !== 'hi' || !q) return q;
  return QUESTION_TEXT_HI[q] ?? q;
}
